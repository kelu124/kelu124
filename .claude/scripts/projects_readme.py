#!/usr/bin/env python3
"""Regroup projects/*.toml into projects/README.md.

Sections: a header with totals, an index by chip / platform tag, the catalogue grouped
by `category` (sorted by stars), and a collapsible list of forks from forks.toml.

Usage:
  python3 .claude/scripts/projects_readme.py          # rebuild projects/README.md
  python3 .claude/scripts/projects_readme.py --stdout # print instead of writing
Stdlib only (Python >= 3.11).
"""
import argparse
import datetime as dt
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROJECTS = ROOT / "projects"
OUT = PROJECTS / "README.md"
FORKS = PROJECTS / "forks.toml"

# category key -> (title, blurb); unknown categories land at the end under their own key
CATEGORIES = {
    "ultrasound-hardware": ("Ultrasound hardware", "Boards and devkits for pulse-echo ultrasound."),
    "ultrasound-software": ("Ultrasound software & libraries", "Drivers, signal processing and probe reverse-engineering."),
    "ultrasound-research": ("Ultrasound research & community", "Reviews, patents, curated lists, community maps."),
    "hardware": ("Other hardware", "Breakouts, PMODs, power and misc electronics."),
    "fpga": ("FPGA", "Gateware, Lattice knowledge bases and experiments."),
    "ai": ("AI & LLM experiments", "Agents, caching, tiny models on micros."),
    "data": ("Data & analysis", "Notebooks, OSINT, mapping, simulations."),
    "web": ("Web & tools", "Sites, templates and small apps."),
    "fun": ("Fun", "Games, toys, side quests."),
    "meta": ("Meta", "This profile and its tooling."),
    "other": ("Other", "Everything else ;)"),
}


def load():
    projects = []
    for f in sorted(PROJECTS.glob("*.toml")):
        if f.name == FORKS.name:
            continue
        with f.open("rb") as h:
            projects.append(tomllib.load(h))
    forks = []
    if FORKS.exists():
        with FORKS.open("rb") as h:
            forks = tomllib.load(h).get("fork", [])
    return projects, forks


def entry(p):
    bits = [f"- **[{p['name']}]({p['url']})**"]
    meta = []
    if p.get("stars"):
        meta.append(f"⭐ {p['stars']}")
    if p.get("forks"):
        meta.append(f"🍴 {p['forks']}")
    if p.get("license"):
        meta.append(p["license"])
    if p.get("archived"):
        meta.append("archived")
    if meta:
        bits.append(" · ".join(meta))
    line = " ".join(bits)
    tags = " ".join(f"`{t}`" for t in p.get("tags", []))
    text = p.get("summary") or p.get("description") or ""
    if tags:
        line += f" {tags}"
    if text:
        line += f"  \n  {text}"
    kws = p.get("keywords") or []
    if kws:
        line += f"  \n  <sub>{', '.join(kws)}</sub>"
    return line


def build_text(projects, forks):
    projects = sorted(projects, key=lambda p: (-p.get("stars", 0), p["name"].lower()))
    total_stars = sum(p.get("stars", 0) for p in projects)
    today = dt.date.today().isoformat()
    L = [
        "# Projects catalogue",
        "",
        f"All my public repositories on GitHub, one [TOML file](.) per project. "
        f"{len(projects)} original projects (⭐ {total_stars} in total) and {len(forks)} forks, "
        f"as of {today}.",
        "",
        "Generated by `.claude/scripts/projects_readme.py` — edit the `.toml` files, not this page.",
        "",
        "## By chip / platform",
        "",
    ]
    by_tag = {}
    for p in projects:
        for t in p.get("tags", []):
            by_tag.setdefault(t, []).append(p)
    for t in sorted(by_tag, key=lambda t: (-len(by_tag[t]), t)):
        names = ", ".join(f"[{p['name']}]({p['url']})" for p in by_tag[t])
        L.append(f"- `{t}` ({len(by_tag[t])}): {names}")
    L.append("")

    L += ["## Catalogue", ""]
    cats = {}
    for p in projects:
        cats.setdefault(p.get("category") or "other", []).append(p)
    order = [c for c in CATEGORIES if c in cats] + sorted(c for c in cats if c not in CATEGORIES)
    for c in order:
        title, blurb = CATEGORIES.get(c, (c, ""))
        L += [f"### {title}", ""]
        if blurb:
            L += [f"_{blurb}_", ""]
        L += [entry(p) for p in cats[c]]
        L.append("")

    uncurated = [p["name"] for p in projects if p.get("curated") is False]
    if uncurated:
        L += ["> Entries still waiting for a hand-written summary: " + ", ".join(uncurated), ""]

    if forks:
        L += [f"<details><summary><b>Forks</b> ({len(forks)})</summary>", ""]
        for f in sorted(forks, key=lambda f: f["name"].lower()):
            d = f" — {f['description']}" if f.get("description") else ""
            L.append(f"- [{f['name']}]({f['url']}){d}")
        L += ["", "</details>", ""]
    return "\n".join(L)


def build():
    projects, forks = load()
    text = build_text(projects, forks)
    OUT.write_text(text)
    return text


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args()
    if args.stdout:
        sys.stdout.write(build_text(*load()))
    else:
        build()
        print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
